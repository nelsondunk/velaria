#!/usr/bin/env python3
"""Turns the first-order spherical-harmonic HRIR set from Resonance Audio (SADIE II subject 002, symmetric,
48 kHz, 256 taps, ACN/SN3D, Apache 2.0) into quest/src/hrir_sh1.h: four float filters. Left ear = sum of the four
filtered components; right ear = the same with the Y (ACN 1) term negated (the set is left/right symmetric).
    python3 quest/tools/mkhrir.py   (from the repository root)"""
import struct, wave, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
w = wave.open(os.path.join(root, "third_party/sadie/sh_hrir_order_1.wav"))
assert (w.getnchannels(), w.getsampwidth(), w.getframerate()) == (4, 2, 48000), w.getparams()
n = w.getnframes()
s = struct.unpack("<%dh" % (n * 4), w.readframes(n))
with open(os.path.join(root, "src/hrir_sh1.h"), "w") as f:
    f.write("// Generated by quest/tools/mkhrir.py from quest/third_party/sadie/sh_hrir_order_1.wav (Resonance Audio's\n"
            "// SADIE II subject 002 first-order SH HRIRs, 48 kHz, Apache 2.0). Do not edit.\n#pragma once\n")
    f.write("namespace vrq {\nconstexpr int kHrirTaps = %d;\n" % n)
    f.write("// [ACN channel W Y Z X][tap]\nconstexpr float kHrirSh1[4][%d] = {\n" % n)
    for c in range(4):
        vals = [s[i * 4 + c] / 32768.0 for i in range(n)]
        f.write("  {" + ", ".join(("%.7g" % v) + ("" if any(ch in "%.7g" % v for ch in ".e") else ".0") + "f" for v in vals) + "},\n")
    f.write("};\n}  // namespace vrq\n")
print("wrote src/hrir_sh1.h: 4 x %d taps" % n)
