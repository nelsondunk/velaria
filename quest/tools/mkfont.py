#!/usr/bin/env python3
"""Bakes Red Hat Text (SIL Open Font License, quest/fonts/) into anti-aliased glyph bitmaps for the headset HUD: quest/src/font_ui.h.

Digits use tabular figures and are forced to one advance so changing numbers don't make the text jitter.
UI v3 (30 Oct 2026) replaced Saira with Red Hat Text; the Saira names (kMedium40 ...) are kept for the call sites.
usage: mkfont.py <out.h>
"""
import sys

from PIL import Image, ImageDraw, ImageFont
from fontTools.ttLib import TTFont

FALLBACK = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"   # arrows and geometric shapes Saira lacks

FONTDIR = __file__.rsplit("/", 2)[0] + "/fonts/"
FONTS = [  # (C++ name, file, pixel size)
    ("kMedium40", "RedHatText-Medium.ttf", 40),
    ("kSemiBold40", "RedHatText-SemiBold.ttf", 40),
    ("kMedium30", "RedHatText-Medium.ttf", 30),
    ("kSemiBold30", "RedHatText-SemiBold.ttf", 30),
    ("kBold36", "RedHatText-Bold.ttf", 36),      # readouts
    ("kBold34", "RedHatText-Bold.ttf", 34),      # ring / arc readouts (v3)
    ("kBold30", "RedHatText-Bold.ttf", 30),      # bar readouts (v3)
    ("kBold26", "RedHatText-Bold.ttf", 26),      # readouts in dials
    ("kSemiBold24", "RedHatText-SemiBold.ttf", 24),   # empty-state line (v3)
    ("kSemiBold22", "RedHatText-SemiBold.ttf", 22),   # chip labels (v3)
    ("kSemiBold20", "RedHatText-SemiBold.ttf", 20),   # meta, status (v3), small labels
    ("kBold18", "RedHatText-Bold.ttf", 18),      # tracked section titles, version tags (v3)
    ("kSemiBold16", "RedHatText-SemiBold.ttf", 16),   # captions (v3)
]
EXTRA = sorted([0xB0, 0xB1, 0xB2, 0xB7, 0xD7, 0x2013, 0x2014, 0x2022, 0x2026, 0x2039, 0x203A, 0x2190, 0x2191, 0x2192, 0x2193, 0x2212, 0x25B2, 0x25B6, 0x25BC, 0x25C0])
CODEPOINTS = list(range(32, 127)) + EXTRA


def bake(name, path, size):
    main = ImageFont.truetype(FONTDIR + path, size)
    cmap = TTFont(FONTDIR + path).getBestCmap()
    fallback = ImageFont.truetype(FALLBACK, int(size * 0.88))
    ascent, descent = main.getmetrics()
    digit_adv = max(main.getlength(d, features=["tnum"]) for d in "0123456789")
    glyphs, bitmap = [], bytearray()
    for cp in CODEPOINTS:
        ch = chr(cp)
        font = main if cp in cmap else fallback
        feats = ["tnum"] if ch.isdigit() else None
        adv = font.getlength(ch, features=feats)
        shift = 0.0
        if ch.isdigit() and font is main:      # one advance for every digit, glyph centred in it
            shift = (digit_adv - adv) / 2
            adv = digit_adv
        # render with generous padding, then trim to the ink
        pad = size
        img = Image.new("L", (int(adv) + 2 * pad, ascent + descent + 2 * pad), 0)
        ImageDraw.Draw(img).text((pad, pad), ch, font=font, fill=255, features=feats)
        bbox = img.getbbox()
        if bbox is None:
            glyphs.append((0, 0, 0, 0, int(round(adv * 64)), len(bitmap)))
            continue
        x0, y0, x1, y1 = bbox
        crop = img.crop(bbox)
        left = x0 - pad + int(round(shift))   # from pen position
        top = (pad + ascent) - y0    # pixels above the baseline
        glyphs.append((x1 - x0, y1 - y0, left, top, int(round(adv * 64)), len(bitmap)))
        bitmap += crop.tobytes()
    return name, size, ascent, descent, glyphs, bitmap


def main():
    out = sys.argv[1]
    with open(out, "w") as f:
        f.write("// Generated by quest/tools/mkfont.py from Red Hat Text (SIL Open Font License 1.1). Do not edit.\n")
        f.write("#pragma once\n#include <cstdint>\n\nnamespace font_ui {\n\n")
        f.write("struct Glyph {\n    int16_t w, h, left, top;   // bitmap size; offset from pen (x) and baseline (up)\n"
                "    int32_t adv64;              // advance in 1/64 px\n    uint32_t off;               // into bitmap\n};\n")
        f.write("struct Font {\n    int size, ascent, descent;\n    const Glyph* glyphs;\n    const uint8_t* bitmap;\n};\n\n")
        f.write("constexpr int kGlyphCount = %d;\n" % len(CODEPOINTS))
        f.write("constexpr uint32_t kCodepoints[kGlyphCount] = {%s};\n\n" % ", ".join(str(c) for c in CODEPOINTS))
        for name, path, size in FONTS:
            n, sz, asc, desc, glyphs, bitmap = bake(name, path, size)
            f.write("const Glyph %sGlyphs[kGlyphCount] = {\n" % n)
            for g in glyphs:
                f.write("    {%d, %d, %d, %d, %d, %d},\n" % g)
            f.write("};\n")
            f.write("const uint8_t %sBitmap[%d] = {\n" % (n, max(1, len(bitmap))))
            for i in range(0, len(bitmap), 32):
                f.write("    " + ",".join(str(b) for b in bitmap[i:i + 32]) + ",\n")
            f.write("};\n")
            f.write("const Font %s = {%d, %d, %d, %sGlyphs, %sBitmap};\n\n" % (n, sz, asc, desc, n, n))
        f.write("}  // namespace font_ui\n")


if __name__ == "__main__":
    main()
